# 5. Restaurant Bill A family orders: Biryani = ₹300 Cool Drinks = ₹100 Ice Cream = ₹150 Calculate: Total bill GST @ 5% Final bill 

biryani = 300
cool_drinks = 100
ice_cream = 150

total_bill = biryani + cool_drinks + ice_cream
gst = total_bill * 0.05
final_bill = total_bill + gst

print("Total Bill: Rs.", total_bill)
print("GST @ 5%: Rs.", gst)
print("Final Bill Amount: Rs.", final_bill)