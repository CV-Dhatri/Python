# 9. Bank Fixed Deposit 
# Principal = ₹50,000 
# Rate = 6% 
# Time = 2 years 
# Calculate: 
# Simple Interest 
# Total Amount 

principal = 50000
rate = 0.06
time = 2

simple_interest = principal * rate * time
total_amount = principal + simple_interest

print("Principal: Rs.", principal)
print("Rate: {}%".format(rate * 100))
print("Time: {} years".format(time))
print("Simple Interest: Rs.", simple_interest)
print("Total Amount: Rs.", total_amount)