# 15. Salary Increment 
# Current salary = ₹40,000 
# Increment = 10% 
# Calculate: 
# Increment amount 
# New salary

current_salary = 40000
increment = 10

increment_amount = current_salary * (increment / 100)
new_salary = current_salary + increment_amount

print("Increment amount: Rs.", increment_amount)
print("New salary: Rs.", new_salary)