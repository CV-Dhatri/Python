# 14. Grocery Store 
# Items: 
# Milk = ₹60 
# Bread = ₹40 
# Eggs = ₹80 
# Calculate: 
# Total bill 
# GST @ 5% 
# Final amount

milk = 60
bread = 40
eggs = 80

total_bill = milk + bread + eggs
gst = total_bill * 0.05
final_amount = total_bill + gst

print("Total bill: Rs.", total_bill)
print("GST @ 5%: Rs.", gst)
print("Final amount to be paid: Rs.", final_amount)