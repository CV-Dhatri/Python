# 3. Employee Salary An employee's basic salary is ₹30,000. Calculate: HRA = 20% DA = 10% Total salary 

basic_salary = 30000
hra = basic_salary * 0.20
da = basic_salary * 0.10

total_salary = basic_salary + hra + da

print("Basic Salary: Rs.", basic_salary)
print("HRA @ 20%: Rs.", hra)
print("DA @ 10%: Rs.", da)
print("Total Salary: Rs.", total_salary)