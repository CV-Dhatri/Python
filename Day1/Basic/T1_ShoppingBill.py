# 1. Shopping Bill A customer buys: Rice = ₹500 Oil = ₹200 Sugar = ₹150 Calculate: Total amount GST @ 18% Final bill amount 

rice = 500
oil = 200
sugar = 150

total_amount = rice + oil + sugar
gst = total_amount * 0.18
final_bill_amount = total_amount + gst

print("Total Amount: Rs.", total_amount)
print("GST @ 18%: Rs.", gst)
print("Final Bill Amount: Rs.", final_bill_amount)